"""Audit label provenance, font support, pixel quality, and conjunct examples.

Pixel and cmap checks cannot establish semantic transcription correctness.
Potential clipping and malformed labels are review candidates, not automatic
proof that a particular Devanagari ligature is wrong.
"""
