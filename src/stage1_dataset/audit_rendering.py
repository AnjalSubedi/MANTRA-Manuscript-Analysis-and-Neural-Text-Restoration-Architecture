def structural_mark_warning(warning):
    """Vowel-sign/virama/nukta defects; keep Vedic accents for source review."""
    return any(0x093A <= int(code, 16) <= 0x094F
               for code in re.findall(r"U\+([0-9A-F]{4})", warning))


def create_screened_manifests(manifest_dir, output_dir, excluded_paths):
    """Write a separate, reversible screening preview without changing labels."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    counts = {}
    for split in ("all", "train", "val", "test"):
        source = Path(manifest_dir) / f"htr_{split}.csv"
        destination = output_dir / source.name
        if source.resolve() == destination.resolve():
            raise ValueError("Screening output must be separate from active manifests")
        with source.open(encoding="utf-8", newline="") as stream:
            reader = csv.DictReader(stream)
            fields = reader.fieldnames
            kept = [row for row in reader if row["image_path"] not in excluded_paths]
        _write_csv(destination, kept, fields, encoding="utf-8")
        counts[split] = len(kept)
    return counts


def _check_pixels(row):
    try:
        return check_single_row(row)
    except Exception as error:
        return {"status": "failed", "reason": "audit_exception", "error": str(error)}


def _write_csv(path, rows, fields, encoding="utf-8-sig"):
    with path.open("w", encoding=encoding, newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def make_visuals(rows, output):
    """Render font sentinels and clean references for real matched images."""
    renderer = get_chromium_renderer()
    fonts = sorted(Path("data/stage1_synthetic/fonts").glob("*.ttf"))
    probes = ["श्री", "सुब्बा", "क्ष त्र ज्ञ श्र", "कि की कु कू कृ", "र्क क्र स्त्र न्द्र"]
    cells = []
    font_results = []
    try:
        for font in fonts:
            images = []
            for text in probes:
                image = renderer.render_text_canvas(text, str(font), 42, 15, 15)
                images.append(image)
                image.save(output / f"probe_{font.stem}_{len(images)}.png")
            width = max(1000, sum(im.width for im in images) + 40)
            strip = Image.new("RGB", (width, 125), "white")
            draw = ImageDraw.Draw(strip)
            draw.text((10, 3), font.stem, fill="black")
            x = 10
            for image in images:
                strip.paste(image, (x, 25))
                x += image.width + 5
            cells.append(strip)
            font_results.append({"font": font.stem, "probes": probes})
        width = max(im.width for im in cells)
        canvas = Image.new("RGB", (width, sum(im.height for im in cells)), "white")
        y = 0
        for strip in cells:
            canvas.paste(strip, (0, y))
            y += strip.height
        canvas.save(output / "font_conjuncts.png")

        # One easy and one hard actual sample per term/font. References use
        # the complete exact label, never a transcription generated by OCR.
        selected = []
        for term in ("श्री", "सुब्बा"):
            for font in fonts:
                candidates = [row for row in rows if term in row["text"] and row["font_name"] == font.stem]
                if not candidates:
                    continue
                ranked = sorted(candidates, key=lambda row: (
                    {"easy": 0, "medium": 1, "hard": 2}.get(row["difficulty_bucket"], 1),
                    len(row["text"]), row["image_path"],
                ))
                for row in (ranked[0], ranked[-1]):
                    if row["image_path"] not in {s["image_path"] for s in selected}:
                        selected.append(row)
        sample_dir = output / "samples"
        sample_dir.mkdir(exist_ok=True)
        entries = []
        for index, row in enumerate(selected):
            with Image.open(row["image_path"]) as source:
                actual = source.convert("RGB")
            size = int(row.get("font_size") or 40)
            reference = renderer.render_text_canvas(
                row["text"], f"data/stage1_synthetic/fonts/{row['font_name']}.ttf", size, 20, 20
            )
            canonical = renderer.render_text_canvas(
                row["text"], "data/stage1_synthetic/fonts/NotoSansDevanagari-Regular.ttf", 36, 20, 20
            )
            panel = Image.new("RGB", (
                max(actual.width, reference.width, canonical.width),
                actual.height + reference.height + canonical.height + 85,
            ), "white")
            draw = ImageDraw.Draw(panel)
            y = 0
            for label, im in [("ACTUAL DATASET IMAGE", actual),
                              ("EXACT LABEL / SAME FONT / NO DEGRADATION", reference),
                              ("EXACT LABEL / NOTO SANS REFERENCE", canonical)]:
                draw.text((5, y + 2), label, fill="black")
                panel.paste(im, (0, y + 22))
                y += im.height + 27
            filename = f"samples/sample_{index:03d}.png"
            panel.save(output / filename)
            entries.append({**row, "comparison_image": filename})
        _write_csv(output / "visual_samples.csv", entries, list(rows[0]) + ["comparison_image"])
        return len(entries)
    finally:
        shutdown_chromium_renderer()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", default=None)
    parser.add_argument("--config", default="configs/stage1_synth100k_config.yaml")
    parser.add_argument("--data-config", default="configs/stage2_data_synth100k.yaml")
    parser.add_argument("--output-dir", default="outputs/rendering_audit_2026-10-27")
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--skip-pixels", action="store_true")
    parser.add_argument("--skip-visuals", action="store_true")
    parser.add_argument("--screen-structural", action="store_true",
                        help="Write separate manifests excluding detached vowel/halant candidates")
    args = parser.parse_args()
    config = yaml.safe_load(Path(args.config).read_text(encoding="utf-8"))
    metadata_path = args.metadata or config["paths"].get(
        "final_metadata", "data/stage1_synthetic/metadata/synthetic_image_metadata_stage1_all_final.csv"
    )
    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    with open(metadata_path, encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream))
    with open(config["paths"].get("final_labels", "data/stage1_synthetic/labels/stage1_all_lines.csv"), encoding="utf-8", newline="") as stream:
        labels = {row["line_id"]: row["text"] for row in csv.DictReader(stream)}
    chars = defaultdict(set)
    issues = []
    counters = Counter()
    for row in rows:
        chars[row["font_name"]].update(row["text"])
        if not font_preserves_devanagari_digits(row["font_name"], row["text"]):
            counters["latin_form_devanagari_digit_rows"] += 1
            issues.append({**row, "issue": "latin_form_devanagari_digits"})
        if row["text"] != row["source_text_rendered"]:
            counters["rendered_text_metadata_mismatch"] += 1
            issues.append({**row, "issue": "rendered_text_metadata_mismatch"})
        if row["line_id"] not in labels:
            counters["retired_or_missing_label_id"] += 1
            issues.append({**row, "issue": "retired_or_missing_label_id"})
        elif row["text"] != labels[row["line_id"]]:
            counters["source_label_mismatch"] += 1
            issues.append({**row, "issue": "source_label_mismatch"})
        warnings = label_warnings(row["text"])
        if warnings:
            counters["suspicious_label_sequence"] += 1
            issues.append({**row, "issue": "; ".join(warnings)})
    font_report = []
    for name, characters in sorted(chars.items()):
        with TTFont(f"data/stage1_synthetic/fonts/{name}.ttf") as font:
            cmap = font.getBestCmap()
            missing = sorted(ch for ch in characters if ch not in " \u200c\u200d" and ord(ch) not in cmap)
            scripts = [record.ScriptTag for record in font["GSUB"].table.ScriptList.ScriptRecord] if "GSUB" in font else []
        counters["fonts_with_missing_codepoints"] += int(bool(missing))
        font_report.append({"font": name, "missing_codepoints": [f"U+{ord(c):04X}" for c in missing], "GSUB_scripts": scripts})
    summary = {"rows": len(rows), "metadata_findings": dict(counters), "fonts": font_report,
               "limitations": "Cmap/provenance/pixel checks do not prove semantic label-to-image equivalence. Visual and OCR discrepancies require review; conjunct variation is not automatically an error."}
    (output / "metadata_audit.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    fields = ["issue", "image_path", "line_id", "text", "font_name", "degradation_profile"]
    _write_csv(output / "label_review.csv", issues, fields)
    strict = [row for row in issues if structural_mark_warning(row["issue"])]
    _write_csv(output / "strict_label_review.csv", strict, fields)
    summary["detached_vowel_halant_rows"] = len({row["image_path"] for row in strict})
    if args.screen_structural:
        data_config = yaml.safe_load(Path(args.data_config).read_text(encoding="utf-8"))
        summary["screened_counts"] = create_screened_manifests(
            Path(data_config["paths"]["manifest_all"]).parent, output / "screened_manifests",
            {row["image_path"] for row in strict},
        )
    print("Metadata audit: " + json.dumps(dict(counters)), flush=True)
    if not args.skip_visuals:
        summary["visual_samples"] = make_visuals(rows, output)
        print(f"Visual comparisons ready: {summary['visual_samples']}", flush=True)
    if not args.skip_pixels:
        reasons = Counter()
        flagged = []
        with ProcessPoolExecutor(max_workers=args.workers, mp_context=multiprocessing.get_context("spawn")) as pool:
            for index, result in enumerate(pool.map(_check_pixels, rows, chunksize=128)):
                if result["status"] != "passed":
                    reason = result.get("reason", "unknown")
                elif result.get("is_unreadable_risk"):
                    reason = "low_readability_review"
                else:
                    reason = ""
                if reason:
                    reasons[reason] += 1
                    flagged.append({**rows[index], "issue": reason})
                if (index + 1) % 10000 == 0:
                    print(f"Pixel checks: {index + 1}/{len(rows)}; review candidates: {len(flagged)}", flush=True)
        summary["pixel_review_reasons"] = dict(reasons)
        summary["pixel_rows_checked"] = len(rows)
        _write_csv(output / "pixel_review.csv", flagged, fields)
    (output / "audit_summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print("Audit complete: " + str(output), flush=True)


if __name__ == "__main__":
    main()
